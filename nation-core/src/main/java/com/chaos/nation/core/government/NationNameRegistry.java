  private NationNameRegistry() {}

  /** 归一化：去掉首尾空白、折叠内部空白、转小写、统一全角空格，便于绕过检测的大小写/空格变体。 */
  public static String normalize(String raw) {
    if (raw == null) return "";
    return raw.replace('\u3000', ' ').trim().replaceAll("\\s+", " ").toLowerCase(Locale.ROOT);
  }

  /** 校验名称是否可注册。 */
  public static Result validate(String rawName) {
    String name = normalize(rawName);
    if (name.isEmpty() || name.length() > 48) {
      return Result.denied(ErrorCode.INVALID_ARGUMENT, "国家名称长度必须在 1..48 之间");
    }
    if (RESERVED_NAMES.contains(name)) {
      return Result.denied(ErrorCode.NAME_RESTRICTED, "为符合相关国家的法律法规，该名称不可注册");
    }
    return Result.ok();
  }

  public static boolean isReserved(String rawName) {
    return RESERVED_NAMES.contains(normalize(rawName));
  }
